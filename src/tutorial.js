export const TUTORIAL_KEY = 'tutorialStep'

// 가장 멀리 간 단계(1부터). 저장된 게 없으면 0.
export function readTutorialStep() {
  try {
    return Number(localStorage.getItem(TUTORIAL_KEY)) || 0
  } catch {
    return 0
  }
}
export function saveTutorialStep(n) {
  try {
    if (n > readTutorialStep()) localStorage.setItem(TUTORIAL_KEY, String(n))
  } catch {
    /* 저장 못 해도 진행에는 문제없음 */
  }
}
